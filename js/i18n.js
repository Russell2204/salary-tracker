  init() {
    let lang = "ru";
    try {
      const saved = localStorage.getItem(this.KEY);
      if (saved === "ru" || saved === "uz") lang = saved;
    } catch (_) {}
    this.setLang(lang, false);
  },

  setLang(lang, persist = true) {
    this.lang = lang === "uz" ? "uz" : "ru";
    document.documentElement.setAttribute("lang", this.lang === "uz" ? "uz" : "ru");
    document.documentElement.setAttribute("data-lang", this.lang);
    if (persist) {
      try {
        localStorage.setItem(this.KEY, this.lang);
      } catch (_) {}
    }
    this.applyDom();
  },

  toggle() {
    this.setLang(this.lang === "ru" ? "uz" : "ru", true);
  },

  t(key, vars = {}) {
    const dict = this.dictionaries[this.lang] || this.dictionaries.ru;
    let text = dict[key] ?? this.dictionaries.ru[key] ?? key;
    Object.keys(vars).forEach((k) => {
      text = text.replace(new RegExp(`\\{${k}\\}`, "g"), String(vars[k]));
    });
    return text;
  },

  categoryName(cat) {
    if (!cat) return "—";
    const key = cat.key || this.seedNameToKey[cat.name];
    if (key) return this.t(`cat.${key}`);
    return cat.name;
  },

  applyDom() {
    document.querySelectorAll("[data-i18n]").forEach((el) => {
      el.textContent = this.t(el.getAttribute("data-i18n"));
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
      el.setAttribute("placeholder", this.t(el.getAttribute("data-i18n-placeholder")));
    });
    document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
      el.setAttribute("aria-label", this.t(el.getAttribute("data-i18n-aria")));
    });
    document.querySelectorAll("[data-i18n-title]").forEach((el) => {
      el.setAttribute("title", this.t(el.getAttribute("data-i18n-title")));
    });
    document.title = this.t("doc.title");
  },
